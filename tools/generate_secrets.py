#!/usr/bin/env python3
"""
generate_secrets.py — Generate cryptographically secure EDR secrets.

Usage:
    python generate_secrets.py              # print to stdout
    python generate_secrets.py --write      # write directly to .env
    python generate_secrets.py --write --force  # overwrite existing .env

Run this once before your first deployment.  The generated values are
printed as ready-to-use environment variable assignments and optionally
written to a .env file.

IMPORTANT: Keep the generated .env file private — treat it like a password.
Never commit it to version control.  The .gitignore already excludes .env.
"""

import os
import sys
import secrets
import argparse
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]


def generate() -> dict:
    return {
        "EDR_API_KEY":    secrets.token_hex(32),       # 256-bit agent key
        "EDR_JWT_SECRET": secrets.token_urlsafe(48),   # 384-bit JWT secret
        "FLASK_SECRET_KEY": secrets.token_hex(32),     # 256-bit session key
    }


def print_secrets(vals: dict):
    print()
    print("╔══════════════════════════════════════════════════════════════╗")
    print("║            EDR — Generated Secrets                          ║")
    print("╚══════════════════════════════════════════════════════════════╝")
    print()
    print("  Copy these into your .env file or set them as environment variables.")
    print("  Keep them private — they protect your EDR server.\n")
    for k, v in vals.items():
        print(f"  {k}={v}")
    print()
    print("  Quick export (Linux/macOS):")
    for k, v in vals.items():
        print(f"    export {k}={v}")
    print()
    print("  Quick export (PowerShell):")
    for k, v in vals.items():
        print(f"    $env:{k}='{v}'")
    print()


def write_env(vals: dict, force: bool = False):
    env_path = HERE / ".env"
    example_path = HERE / ".env.example"

    if env_path.exists() and not force:
        print(f"  ⚠  {env_path} already exists.")
        print("  Use --force to overwrite, or edit it manually.")
        return False

    # Start from the example template if it exists
    if example_path.exists():
        template = example_path.read_text(encoding="utf-8")
        for k, v in vals.items():
            # Replace the placeholder line for each key
            lines = template.splitlines()
            new_lines = []
            for line in lines:
                if line.startswith(f"{k}=") or line.startswith(f"# {k}="):
                    new_lines.append(f"{k}={v}")
                else:
                    new_lines.append(line)
            template = "\n".join(new_lines)
        env_path.write_text(template, encoding="utf-8")
    else:
        # Write minimal .env
        lines = [
            "# Generated by generate_secrets.py — keep private, never commit\n",
        ]
        for k, v in vals.items():
            lines.append(f"{k}={v}\n")
        env_path.write_text("".join(lines), encoding="utf-8")

    print(f"  ✅  Written to {env_path}")
    print(f"  Load with: export $(grep -v '^#' .env | xargs)  (Linux/macOS)")
    print(f"             or use your deployment tool's .env loader")
    return True


def main():
    parser = argparse.ArgumentParser(
        description="Generate secure EDR secrets."
    )
    parser.add_argument("--write", action="store_true",
                        help="Write generated secrets to .env")
    parser.add_argument("--force", action="store_true",
                        help="Overwrite existing .env without prompting")
    args = parser.parse_args()

    vals = generate()
    print_secrets(vals)

    if args.write:
        write_env(vals, force=args.force)


if __name__ == "__main__":
    main()
